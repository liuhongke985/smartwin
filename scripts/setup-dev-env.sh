set -euo pipefail

LOG_PREFIX="[setup-dev-env]"
log() { echo "$LOG_PREFIX $1"; }

install_hint() {
  local cmd="$1"
  if ! command -v "$cmd" >/dev/null 2>&1; then
    log "未安装 $cmd，请按团队规范安装"
  else
    log "已检测到 $cmd"
  fi
}

main() {
  log "开始检查开发环境"
  for c in git docker docker-compose java python3 node npm; do
    install_hint "$c"
  done
  mkdir -p .cache .tmp logs
  cp -n .env.example .env 2>/dev/null || true
  log "开发环境检查完成"
}

